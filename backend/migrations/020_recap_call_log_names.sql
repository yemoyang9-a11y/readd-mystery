-- 근거: 2026-11-17 파이프라인 조사 제안 4 — 리캡 출력에 "허용 사전(기준 쪽수 이하 인물명·
--       별칭)에도, 리캡 입력 자료에도 없는 이름꼴 낱말"이 생겼는지 센다(recap-names.ts).
--       리캡은 LLM 1회이고 재생성이 없어, 걸려도 막거나 고치지 않고 이 로그에만 남긴다.
--       걸렸을 때의 처리(미노출·재생성·로그만)는 측정값을 본 뒤에 정한다.
-- 조항: NFR-OBS-002 🚦 (리캡 호출 로그) · FR-RCP-001 🚦 (환각 금지)
--
-- ⚠️ 두 컬럼 모두 NULL 허용이다. NULL = 측정하지 않음(이 마이그레이션 전 행, 또는 사전
--    조회 실패). 0 / 빈 배열 = 측정했고 걸린 것이 없음. 기존 데이터는 고치지 않는다.
-- ⚠️ unknown_names는 사람이 오탐 비율을 확인하기 위한 값이다. 이름꼴 판정은 낱말 모양만
--    보는 어림 규칙이라 일반 명사가 섞일 수 있다.
-- ⚠️ scripts/migrate.js는 매번 전 파일을 다시 실행하므로 IF NOT EXISTS로 멱등하게 쓴다.
-- =============================================================================

ALTER TABLE recap_call_log
    -- 사전·입력 자료 어디에도 없는 이름꼴 낱말의 수 (중복 제거)
    ADD COLUMN IF NOT EXISTS unknown_name_count INTEGER CHECK (unknown_name_count >= 0),
    -- 그 낱말 목록
    ADD COLUMN IF NOT EXISTS unknown_names      TEXT[];
