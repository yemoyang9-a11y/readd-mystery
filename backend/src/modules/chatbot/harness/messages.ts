/**
 * 대표 지시 2026-11-18 — 독자가 노트를 보여 달라고 했는데 기준 쪽수(K) 이하에 적은 노트가 없을 때.
 * "노트가 안 보인다"고 하지 않고, 노트는 차례로 읽은 쪽까지 적은 것만 같이 본다고 그대로 말한다.
 * K보다 뒤 쪽에 노트가 있는지는 조회하지 않으므로(절대 규칙 7) "혹시 … 있다면"으로만 말한다.
 */
export function readerNotesEmptyAnswer(cutoff: number): string {
  if (cutoff < 1) {
    return '아직 차례로 읽으신 쪽이 없어서 제가 같이 볼 수 있는 노트가 없어요. 1쪽부터 읽어 나가시면 읽으신 쪽까지 적은 노트를 같이 볼 수 있어요.';
  }
  return `제가 같이 볼 수 있는 노트는 차례로 읽으신 ${cutoff}쪽까지 적은 것뿐인데, 거기까지는 아직 노트가 없어요. 혹시 그보다 뒤 쪽에 적어 두신 노트가 있다면, 그 쪽까지 차례로 읽으신 뒤에 같이 볼 수 있어요.`;
}

